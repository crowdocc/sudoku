/// Geçici deneme bulmacaları. Bulmaca bankası sonraki adımlarda gelecek.
/// 0 = boş hücre. Her bulmacanın tek çözümü doğrulandı.
enum GameMode { classic, killer }

class Cage {
  final int sum;
  final List<int> cells;

  const Cage(this.sum, this.cells);
}

class Puzzle {
  final GameMode mode;
  final int number;
  final String givens;
  final String solution;

  /// Killer kafesleri: "toplam:hücre,hücre;toplam:hücre,..." biçiminde.
  final String cageSpec;

  const Puzzle(this.mode, this.number, this.givens, this.solution,
      {this.cageSpec = ''});

  List<Cage> get cages {
    if (cageSpec.isEmpty) return const <Cage>[];
    return cageSpec.split(';').map((part) {
      final pieces = part.split(':');
      final cells = pieces[1].split(',').map(int.parse).toList();
      return Cage(int.parse(pieces[0]), cells);
    }).toList();
  }
}

